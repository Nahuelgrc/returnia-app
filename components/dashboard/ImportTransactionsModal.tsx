"use client";
import React, { useState } from "react";
import { Modal } from "@/components/ui/Modal";
import {
  CSV_COLUMNS,
  MAX_IMPORT_BYTES,
  MAX_IMPORT_ROWS,
  type ImportResult,
} from "@/lib/transactions-csv";

interface ImportTransactionsModalProps {
  isOpen: boolean;
  onClose: () => void;
  onImport: (content: string) => Promise<ImportResult>;
}

const EXAMPLE = `${CSV_COLUMNS.join(",")}
2024-01-10T12:00:00Z,buy,crypto,BTC,0.5,42000,First buy
2024-02-01T09:30:00Z,sell,stock,AAPL,3,150.25,"Sold, partial"`;

const readFile = (file: File) =>
  new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result ?? ""));
    reader.onerror = () => reject(reader.error);
    reader.readAsText(file);
  });

export const ImportTransactionsModal = ({
  isOpen,
  onClose,
  onImport,
}: ImportTransactionsModalProps) => {
  const [file, setFile] = useState<File | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [result, setResult] = useState<ImportResult | null>(null);
  const [fileError, setFileError] = useState<string | null>(null);

  const handleClose = () => {
    setFile(null);
    setResult(null);
    setFileError(null);
    onClose();
  };

  const handleFile = (selected: File | undefined) => {
    setResult(null);
    setFileError(null);
    setFile(null);
    if (!selected) return;
    if (selected.size > MAX_IMPORT_BYTES) {
      setFileError(`The file is too large (max ${MAX_IMPORT_BYTES / 1024} KB)`);
      return;
    }
    setFile(selected);
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!file) return;
    setIsSubmitting(true);
    setResult(null);
    try {
      setResult(await onImport(await readFile(file)));
    } catch {
      setResult({ error: "Error importing the transactions" });
    } finally {
      setIsSubmitting(false);
    }
  };

  const imported = result && "success" in result ? result.imported : null;
  const error = fileError ?? (result && "error" in result ? result.error : null);
  const errors = result && "errors" in result ? result.errors : null;

  return (
    <Modal
      isOpen={isOpen}
      onClose={handleClose}
      title="Import Transactions"
      disableClose={isSubmitting}
    >
      <form onSubmit={handleSubmit} className="flex flex-col gap-4">
        <div className="text-xs text-slate-500 dark:text-slate-400 flex flex-col gap-2">
          <p>
            CSV with columns: <span className="font-mono">{CSV_COLUMNS.join(", ")}</span>.
            Comments is optional. Dates in ISO 8601, type buy/sell, assetType
            crypto/stock. Max {MAX_IMPORT_ROWS} rows and {MAX_IMPORT_BYTES / 1024} KB.
            All rows are imported or none. The file generated by Export CSV is valid.
          </p>
          <pre className="bg-slate-100 dark:bg-slate-900 rounded-lg p-3 overflow-x-auto text-[11px] leading-relaxed">
            {EXAMPLE}
          </pre>
        </div>

        <input
          type="file"
          accept=".csv,text/csv"
          aria-label="CSV file"
          onChange={(e) => handleFile(e.target.files?.[0])}
          disabled={isSubmitting}
          className="text-sm"
        />

        {error && (
          <div
            role="alert"
            className="rounded-lg border border-red-500/30 bg-red-500/10 px-4 py-3 text-sm text-red-400"
          >
            {error}
          </div>
        )}

        {errors && (
          <div
            role="alert"
            className="rounded-lg border border-red-500/30 bg-red-500/10 px-4 py-3 text-sm text-red-400"
          >
            <p className="font-bold mb-2">
              Nothing was imported. Fix these rows and try again:
            </p>
            <ul className="max-h-48 overflow-y-auto list-disc pl-5 flex flex-col gap-1">
              {errors.map((e, i) => (
                <li key={i}>
                  Row {e.row}: {e.message}
                </li>
              ))}
            </ul>
          </div>
        )}

        {imported !== null && (
          <div
            role="status"
            className="rounded-lg border border-green-500/30 bg-green-500/10 px-4 py-3 text-sm text-green-400"
          >
            {imported} {imported === 1 ? "transaction" : "transactions"} imported.
          </div>
        )}

        <div className="flex justify-end gap-3">
          <button
            type="button"
            onClick={handleClose}
            disabled={isSubmitting}
            className="px-4 py-2 text-sm font-bold text-slate-500 hover:text-foreground disabled:opacity-50"
          >
            {imported !== null ? "Close" : "Cancel"}
          </button>
          {imported === null && (
            <button
              type="submit"
              disabled={!file || isSubmitting}
              className="px-6 py-2 bg-primary hover:bg-primary/90 text-white text-sm font-bold rounded-xl shadow-lg shadow-primary/20 transition-all disabled:opacity-70 disabled:cursor-not-allowed"
            >
              {isSubmitting ? "Importing..." : "Import"}
            </button>
          )}
        </div>
      </form>
    </Modal>
  );
};
